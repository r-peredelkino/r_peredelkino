"""Independent checks against source photo, not only internal coordinate equality."""
import json
from pathlib import Path
from PIL import Image
from shapely.geometry import Polygon,Point,LineString
j=json.loads(Path('dist/complex-footprints.js').read_text().split('=',1)[1].rstrip(';\n'))
im=Image.open('tools/reference/numbered-plan.jpg').convert('RGB');ox,oz=j['transform']['origin'];scale=j['transform']['scale'];pod=Polygon(j['podium']['outer']);fan=Polygon(j['fan']['outer'],j['fan']['holes']);arena=Polygon(j['arena']['outer']);kids=Polygon(j['kindergarten']['outer'])
assert pod.is_valid and fan.is_valid and fan.geom_type=='Polygon' and len(fan.interiors)==5
assert arena.difference(pod).area<.01
coverage=[]
for b in j['buildings']:
 p=Polygon([[x+b['x'],z+b['z']] for x,z in b['shape']]);assert p.difference(pod).area<.02
 if b['id']==0:assert not p.intersects(fan)
 else:assert p.intersection(fan).area>10
 x0,z0,x1,z1=p.bounds;hits=total=0
 for i in range(45):
  for k in range(45):
   x=x0+(x1-x0)*(i+.5)/45;z=z0+(z1-z0)*(k+.5)/45
   if not p.contains(Point(x,z)):continue
   r,g,blue=im.getpixel((round(x/scale+ox),round(z/scale+oz)));total+=1;hits+=r-g>15 and r-blue>12
 ratio=hits/total;assert ratio>.9,f'Building {b["id"]} falls outside source footprint: {ratio:.2f}';coverage.append(round(ratio,3))
# Generated by the same curves used to animate the walkers in the client.
routes=json.loads(Path('/tmp/engineering-routes.json').read_text())
clearances=[]
for samples in routes:
 route=LineString(samples);dist=min(route.distance(pod),route.distance(kids));assert dist>1.35, f'Path crosses a building or its edge: {dist}';clearances.append(round(dist,2))
print('PASS: photo footprint coverage',coverage,'continuous podium + 5 roof openings; path clearance',clearances)
